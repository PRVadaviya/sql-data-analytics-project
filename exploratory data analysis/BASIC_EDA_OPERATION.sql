-- STEP 5: MAGNITUDE ANALTSIS 


-- FIND TOTAL CUSOMER BY COUNTRY

SELECT 
	COUNTRY,
	COUNT(customer_key) AS TOTAL_CUSTOMERS
FROM GOLD.dim_customers
GROUP BY country
ORDER BY TOTAL_CUSTOMERS DESC

--FIND TOTAL CUSOMER BY GENDER

SELECT 
	gender,
	COUNT(customer_key) AS TOTAL_CUSTOMERS
FROM GOLD.dim_customers
GROUP BY gender
ORDER BY TOTAL_CUSTOMERS DESC

-- FIND TOTAL PRODUCTS BY CATEGORY

SELECT 
	category,
	COUNT(product_key) AS TOTAL_PRODUCTS
FROM GOLD.dim_products
GROUP BY category
ORDER BY TOTAL_PRODUCTS DESC

-- WHAT IS THE AVERAGE COST IN EACH CATEGORY

SELECT 
	category,
	avg(cost) AS AVERAGE_COST
FROM GOLD.dim_products
GROUP BY category
ORDER BY AVERAGE_COST DESC

--WHAT IS THE TOTAL REVENUE GENERATED FROM EACH CATEGORY

SELECT 
	category,
	SUM(SLS.sales_amount) AS TOTAL_REVENUE
FROM GOLD.dim_products PDT
RIGHT JOIN GOLD.fact_sales SLS
ON PDT.product_key = SLS.product_key
GROUP BY PDT.category
ORDER BY TOTAL_REVENUE DESC

--WHAT IS THE TOTAL REVENUE GENERATED BY EACH CUSTOMERS

SELECT 
	CST.customer_id,
	SUM(SLS.sales_amount) AS TOTAL_REVENUE
FROM GOLD.dim_customers CST
RIGHT JOIN GOLD.fact_sales SLS
ON CST.customer_key = SLS.customer_key
GROUP BY CST.customer_id
--ORDER BY customer_id
ORDER BY TOTAL_REVENUE DESC

-- WHAT IS THE DISTRIBUTION OF ITEMS SOLD ACROSS COUNTRY

SELECT 
	CST.COUNTRY,
	SUM(SLS.quantity) AS TOTAL_QUANTITY
FROM GOLD.dim_customers CST
RIGHT JOIN GOLD.fact_sales SLS
ON CST.customer_key = SLS.customer_key
GROUP BY CST.country
ORDER BY TOTAL_QUANTITY DESC


-- STEP 6: RANKING ANALYSIS

-- WHICH 5 PRODUCTS GENERATE MOST REVANUE

SELECT TOP 5
	PDT.product_name,
	SUM(SLS.sales_amount) AS TOTAL_REVENUE
FROM GOLD.dim_products PDT
RIGHT JOIN GOLD.fact_sales SLS
ON PDT.product_key = SLS.product_key
GROUP BY PDT.product_id,PDT.product_name
ORDER BY TOTAL_REVENUE DESC

		-- USING WINDOW FUNCTION 
		SELECT *
		FROM (
			SELECT
			PDT.product_name,
			SUM(SLS.sales_amount) AS TOTAL_REVENUE,
			ROW_NUMBER() OVER (ORDER BY SUM(SLS.sales_amount) DESC) AS RANK_PRODUCTS
			FROM GOLD.dim_products PDT
			RIGHT JOIN GOLD.fact_sales SLS
			ON PDT.product_key = SLS.product_key
			GROUP BY PDT.product_name
			)T
		WHERE RANK_PRODUCTS <= 5

-- WHAT ARE THE 5 WORST PERFORMING PRODUCTS IN TERMS OF SALES

SELECT TOP 5
	PDT.product_name,
	SUM(SLS.sales_amount) AS TOTAL_REVENUE
FROM GOLD.dim_products PDT
RIGHT JOIN GOLD.fact_sales SLS
ON PDT.product_key = SLS.product_key
GROUP BY PDT.product_id,PDT.product_name
ORDER BY TOTAL_REVENUE 

-- FIND TOP 10 CUSTOMERS WHO HAVE GENERATED HIGHEST REVENUE

SELECT * 
FROM 
	(SELECT 
		CST.customer_key,
		CST.first_name,
		CST.last_name,
		SUM(SLS.sales_amount) AS TOTAL_SALES_AMOUNT,
		DENSE_RANK() OVER (ORDER BY SUM(SLS.sales_amount) DESC) AS RANK_CUSTOMER
	FROM GOLD.dim_customers CST
	RIGHT JOIN GOLD.fact_sales SLS
	ON CST.customer_key = SLS.customer_key
	GROUP BY CST.customer_key,CST.first_name,CST.last_name
	)T
WHERE RANK_CUSTOMER <=10

--THE 3 CUSTOMERS WITH THE FEWEST ORDER PLACED 

SELECT * 
FROM 
	(SELECT 
		CST.customer_key,
		CST.first_name,
		CST.last_name,
		COUNT(DISTINCT order_number) AS TOTAL_ORDER,
		DENSE_RANK() OVER (ORDER BY COUNT(order_number)) AS RANK_CUSTOMER
	FROM GOLD.dim_customers CST
	RIGHT JOIN GOLD.fact_sales SLS
	ON CST.customer_key = SLS.customer_key
	GROUP BY CST.customer_key,CST.first_name,CST.last_name
	)T
WHERE RANK_CUSTOMER <=3