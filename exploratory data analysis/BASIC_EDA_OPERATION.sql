-- STEP:1 JUST FOR THE DATABASE EXPLORATION


SELECT * FROM INFORMATION_SCHEMA.TABLES

SELECT * FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'FACT_SALES'


-- STEP 2: DIMENSION EXPLORATION


SELECT * FROM gold.dim_customers;
SELECT * FROM gold.dim_products;
SELECT * FROM gold.fact_sales;

-- EXPLORE ALL COUNTRY OUR CUSTOMER COME FROM.
SELECT country
FROM gold.dim_customers
GROUP BY country

--EXPLORE ALL CATEGORIES "THE MAJOR DIVISIONS"
SELECT category
FROM GOLD.dim_products
GROUP BY category

SELECT DISTINCT category, subcategory, product_name
FROM GOLD.dim_products
ORDER BY 1,2,3



-- STEP 3: FIND THE DATE OF THE FIRST AND LAST ORDER



SELECT MIN(ORDER_DATE) FROM gold.fact_sales;
SELECT MAX(ORDER_DATE) FROM gold.fact_sales;

-- HOW MANY YEAR OF SALES ARE AVAILABLE (4 YEAR)
SELECT 
	MIN(ORDER_DATE) AS FIRST_ORDER,
	MAX(ORDER_DATE) AS LAST_ORDER,
	DATEDIFF(YEAR,MIN(ORDER_DATE),MAX(ORDER_DATE)) AS ORDER_RANGE_YEARS
FROM gold.fact_sales;

-- FIND YOUNGEST AND OLDEST CUSTOMER
SELECT 
	MIN(birthdate) AS YOUNGEST_CUSTOMER,
	DATEDIFF(YEAR,MIN(birthdate),GETDATE()) AS YONGEST_CUSTOMER,
	MAX(birthdate) AS  OLDEST_CUSTOMER,
	DATEDIFF(YEAR,MAX(birthdate),GETDATE()) AS OLDEST_CUSTOMER
FROM gold.dim_customers


-- STEP 4: MEASURE EXPLORATION


-- FIND THE TOTAL SALES
SELECT 
	SUM(sales_amount) AS TOTAL_SALES
FROM gold.fact_sales

--FIND HOW MANY ITEM ARE SOLD
SELECT
	SUM(quantity) AS SOLD_ITEM
FROM gold.fact_sales

--FIND AVERAGE SELLING PRICE
SELECT 
	AVG(price) AS AVG_SELLING_PRICE
FROM gold.fact_sales

-- FIND THE TOTAL NUMBER OF THE ORDERS
SELECT
	COUNT(order_number) AS TOTAL_ORDERS,
	COUNT(DISTINCT order_number) AS TOTAL_UNIQUE_ORDERS
FROM gold.fact_sales;


-- FIND THE TOTAL NUMBER OF THE PRODUCTS
SELECT
	COUNT(product_key) AS TOTAL_PRODUCTS,
	COUNT(DISTINCT product_key) AS TOTAL_UNIQUE_PRODUCTS,
	COUNT(DISTINCT product_name) AS TOTAL_UNIQUE_PRODUCTS_BY_NAME
FROM gold.dim_products;

-- FIND THE TOTAL NUMBER OF THE CUSTOMER 
SELECT 
	COUNT(customer_key) AS TOTAL_CUSTOMER
FROM GOLD.dim_customers


-- FIND THE TOTAL NUMBER OF THE CUSTOMER THAT HAS PLACED AN ORDER 
SELECT
	COUNT(customer_key) AS TOTAL_CUSTOMER,
	COUNT(DISTINCT customer_key) AS TOTAL_UNIQUE_CUSTOMER
FROM gold.dim_customers;

